use std::collections::BTreeSet;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn collect_json(directory: &Path, root: &Path, paths: &mut Vec<PathBuf>) {
    let entries = fs::read_dir(directory)
        .unwrap_or_else(|error| panic!("could not read {}: {error}", directory.display()));
    for entry in entries {
        let path = entry
            .unwrap_or_else(|error| {
                panic!(
                    "could not read an entry in {}: {error}",
                    directory.display()
                )
            })
            .path();
        if path.is_dir() {
            collect_json(&path, root, paths);
        } else if path.extension().and_then(|extension| extension.to_str()) == Some("json") {
            println!("cargo:rerun-if-changed={}", path.display());
            paths.push(
                path.strip_prefix(root)
                    .expect("component vector must be below its root")
                    .to_owned(),
            );
        }
    }
}

fn identifier(text: &str) -> String {
    text.chars()
        .map(|character| {
            if character.is_ascii_alphanumeric() {
                character.to_ascii_lowercase()
            } else {
                '_'
            }
        })
        .collect()
}

fn test_names(path: &Path) -> (String, String) {
    let mut parts = path.iter();
    let component = parts
        .next()
        .expect("component vector path has no component")
        .to_string_lossy();
    let description = parts.collect::<PathBuf>().with_extension("");
    let module = format!("{}_conformance", identifier(&component));
    let mut test = identifier(&description.to_string_lossy());
    if test
        .chars()
        .next()
        .is_some_and(|character| character.is_ascii_digit())
    {
        test.insert_str(0, "case_");
    }
    (module, test)
}

fn main() {
    let root = Path::new("tests/vectors/component");
    println!("cargo:rerun-if-changed={}", root.display());

    let mut paths = Vec::new();
    collect_json(root, root, &mut paths);
    paths.sort();
    assert!(!paths.is_empty(), "no component test vectors found");

    let mut names = BTreeSet::new();
    let mut current_module = None;
    let mut generated = String::from("// Generated by build.rs from tests/vectors/component.\n");
    for path in paths {
        let (module, test) = test_names(&path);
        assert!(
            names.insert((module.clone(), test.clone())),
            "component vector test name collision for {}",
            path.display()
        );
        if current_module.as_deref() != Some(module.as_str()) {
            if current_module.is_some() {
                generated.push_str("}\n");
            }
            generated.push_str(&format!(
                "mod {module} {{\nuse crate::component_conformance::run_vector;\n"
            ));
            current_module = Some(module);
        }
        let relative = path
            .iter()
            .map(|part| part.to_string_lossy())
            .collect::<Vec<_>>()
            .join("/");
        generated.push_str(&format!(
            "#[test]\nfn {test}() {{ run_vector(\"{relative}\"); }}\n"
        ));
    }
    generated.push_str("}\n");

    let destination = PathBuf::from(env::var_os("OUT_DIR").expect("OUT_DIR is not set"))
        .join("component_case_tests.rs");
    fs::write(&destination, generated)
        .unwrap_or_else(|error| panic!("could not write {}: {error}", destination.display()));
}
